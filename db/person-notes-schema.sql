-- Run as the memory schema owner. Safe to rerun; never drops existing data.
-- If runtime and owner differ, grant SELECT, INSERT, UPDATE, DELETE on both
-- tables to USER_MEMORY_USER. Do not grant these tables to the /db account.
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'PERSON_NOTE_SCOPES';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PERSON_NOTE_SCOPES (
      SCOPE_ID VARCHAR2(64 CHAR) PRIMARY KEY,
      REVISION_NO NUMBER DEFAULT 0 NOT NULL,
      CONSTRAINT PERSON_SCOPE_REV_CK CHECK (REVISION_NO >= 0)
    )';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'PERSON_NOTES';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PERSON_NOTES (
      NOTE_ID VARCHAR2(36 CHAR) PRIMARY KEY,
      SCOPE_ID VARCHAR2(64 CHAR) NOT NULL REFERENCES PERSON_NOTE_SCOPES(SCOPE_ID),
      GUILD VARCHAR2(32 CHAR) NOT NULL,
      USER_ID VARCHAR2(32 CHAR) NOT NULL,
      CHANNEL VARCHAR2(32 CHAR) NOT NULL,
      NOTE VARCHAR2(499 CHAR) NOT NULL,
      NOTE_HASH VARCHAR2(64 CHAR) NOT NULL,
      SOURCE_KIND VARCHAR2(16 CHAR) NOT NULL,
      SOURCE_ID VARCHAR2(32 CHAR) NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PERSON_NOTE_LENGTH_CK CHECK (LENGTH(NOTE) BETWEEN 1 AND 499),
      CONSTRAINT PERSON_NOTE_SOURCE_CK CHECK (SOURCE_KIND IN (''interaction'', ''message'')),
      CONSTRAINT PERSON_NOTE_DEDUP_UQ UNIQUE (SCOPE_ID, SOURCE_KIND, SOURCE_ID, NOTE_HASH)
    )';
  END IF;
  -- A later self-disclosure may reaffirm an older preference after a correction.
  -- Deduplicate retries of the same input, preserving chronology across inputs.
  SELECT COUNT(*) INTO n FROM USER_CONS_COLUMNS WHERE CONSTRAINT_NAME = 'PERSON_NOTE_DEDUP_UQ';
  IF n = 2 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PERSON_NOTES DROP CONSTRAINT PERSON_NOTE_DEDUP_UQ';
    n := 0;
  END IF;
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PERSON_NOTES ADD CONSTRAINT PERSON_NOTE_DEDUP_UQ
      UNIQUE (SCOPE_ID, SOURCE_KIND, SOURCE_ID, NOTE_HASH)';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'PERSON_NOTES_RECENT_IX';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX PERSON_NOTES_RECENT_IX
      ON PERSON_NOTES (GUILD, USER_ID, CHANNEL, CREATED_AT DESC, NOTE_ID DESC)';
  END IF;
END;
